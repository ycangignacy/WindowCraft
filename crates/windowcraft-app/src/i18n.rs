pub fn t(lang: Language, msg: Msg) -> &'static str {
    match lang {
        Language::En => en(msg),
        Language::Pl => pl(msg),
        Language::De => de(msg),
        Language::Fr => fr(msg),
        Language::Es => es(msg),
        Language::It => it(msg),
        Language::PtBr => pt_br(msg),
        Language::Uk => uk(msg),
    }
}

/// Fills each `{}` in order. Inserted values are never scanned again, so a
/// path that contains braces stays as it is.
fn fill(pattern: &str, values: &[&str]) -> String {
    let mut out = String::with_capacity(pattern.len() + values.iter().map(|value| value.len()).sum::<usize>());
    let mut rest = pattern;
    for value in values {
        let Some(pos) = rest.find("{}") else { break };
        out.push_str(&rest[..pos]);
        out.push_str(value);
        rest = &rest[pos + 2..];
    }
    out.push_str(rest);
    out
}

pub fn format_1(pattern: &str, a: &str) -> String {
    fill(pattern, &[a])
}

pub fn format_2(pattern: &str, a: &str, b: &str) -> String {
    fill(pattern, &[a, b])
}

pub fn format_3(pattern: &str, a: &str, b: &str, c: &str) -> String {
    fill(pattern, &[a, b, c])
}

