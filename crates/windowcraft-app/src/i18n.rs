#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Language {
    En,
    Pl,
    De,
    Fr,
    Es,
    It,
    PtBr,
    Uk,
}

impl Language {
    pub const ALL: &'static [Self] = &[
        Self::En,
        Self::Pl,
        Self::De,
        Self::Fr,
        Self::Es,
        Self::It,
        Self::PtBr,
        Self::Uk,
    ];

    pub fn tag(self) -> &'static str {
        match self {
            Self::En => "en",
            Self::Pl => "pl",
            Self::De => "de",
            Self::Fr => "fr",
            Self::Es => "es",
            Self::It => "it",
            Self::PtBr => "pt-BR",
            Self::Uk => "uk",
        }
    }

    pub fn native_name(self) -> &'static str {
        match self {
            Self::En => "English",
            Self::Pl => "Polski",
            Self::De => "Deutsch",
            Self::Fr => "Français",
            Self::Es => "Español",
            Self::It => "Italiano",
            Self::PtBr => "Português (Brasil)",
            Self::Uk => "Українська",
        }
    }

    pub fn from_tag(tag: &str) -> Option<Self> {
        let tag = tag.trim();
        if tag.eq_ignore_ascii_case("en") {
            Some(Self::En)
        } else if tag.eq_ignore_ascii_case("pl") {
            Some(Self::Pl)
        } else if tag.eq_ignore_ascii_case("de") {
            Some(Self::De)
        } else if tag.eq_ignore_ascii_case("fr") {
            Some(Self::Fr)
        } else if tag.eq_ignore_ascii_case("es") {
            Some(Self::Es)
        } else if tag.eq_ignore_ascii_case("it") {
            Some(Self::It)
        } else if tag.eq_ignore_ascii_case("pt-br")
            || tag.eq_ignore_ascii_case("pt_br")
            || tag.eq_ignore_ascii_case("pt")
        {
            Some(Self::PtBr)
        } else if tag.eq_ignore_ascii_case("uk") {
            Some(Self::Uk)
        } else {
            None
        }
    }

    pub fn from_langid(langid: u16) -> Self {
        let primary = langid & 0x03ff;
        match primary {
            0x15 => Self::Pl,
            0x07 => Self::De,
            0x0c => Self::Fr,
            0x0a => Self::Es,
            0x10 => Self::It,
            0x16 => Self::PtBr,
            0x22 => Self::Uk,
            0x09 => Self::En,
            _ => Self::En,
        }
    }

    pub fn plural_form(self, count: usize) -> PluralForm {
        match self {
            Self::Pl | Self::Uk => {
                let n10 = count % 10;
                let n100 = count % 100;
                if n10 == 1 && n100 != 11 {
                    PluralForm::One
                } else if (2..=4).contains(&n10) && !(12..=14).contains(&n100) {
                    PluralForm::Few
                } else {
                    PluralForm::Many
                }
            }
            Self::Fr => {
                if count <= 1 {
                    PluralForm::One
                } else {
                    PluralForm::Many
                }
            }
            _ => {
                if count == 1 {
                    PluralForm::One
                } else {
                    PluralForm::Many
                }
            }
        }
    }

    pub fn plural<'a>(self, count: usize, one: &'a str, few: &'a str, many: &'a str) -> &'a str {
        match self.plural_form(count) {
            PluralForm::One => one,
            PluralForm::Few => match self {
                Self::Pl | Self::Uk => few,
                _ => many,
            },
            PluralForm::Many => many,
        }
    }
}

impl fmt::Display for Language {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.native_name())
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PluralForm {
    One,
    Few,
    Many,
}

